export function buildWalls(rawLayout) {
  const layout = normalizeLayout(rawLayout);
  const { variant, bathX, bathY, bathW, bathTop, bathBottom, hallX, hallY } = layout;

  const hallWalls = [
    { id: 'p-hall-v', a: { x: hallX, y: hallY }, b: { x: hallX, y: INNER_D }, t: WALL_GYPSUM, kind: 'partition' },
    { id: 'p-hall-h', a: { x: 0, y: hallY }, b: { x: hallX, y: hallY }, t: WALL_GYPSUM, kind: 'partition' }
  ];

  if (variant === 'bathLeft') {
    return [
      ...OUTER_WALLS,
      // Санузел у западной стены: правая и нижняя грани — перегородки.
      // Верхняя грань становится перегородкой, только если санузел отодвинут
      // от северной стены (например, чтобы не залезть на существующее окно).
      { id: 'p-bath-v', a: { x: bathW, y: bathTop }, b: { x: bathW, y: bathBottom }, t: WALL_GYPSUM, kind: 'partition' },
      { id: 'p-bath-h', a: { x: 0, y: bathBottom }, b: { x: bathW, y: bathBottom }, t: WALL_GYPSUM, kind: 'partition' },
      ...(bathTop > 0.01
        ? [{ id: 'p-bath-t', a: { x: 0, y: bathTop }, b: { x: bathW, y: bathTop }, t: WALL_GYPSUM, kind: 'partition' }]
        : []),
      ...hallWalls
    ];
  }

  return [
    ...OUTER_WALLS,
    // Санузел в правом верхнем углу
    { id: 'p-bath-v', a: { x: bathX, y: 0 }, b: { x: bathX, y: bathY }, t: WALL_GYPSUM, kind: 'partition' },
    { id: 'p-bath-h', a: { x: bathX, y: bathY }, b: { x: INNER_W, y: bathY }, t: WALL_GYPSUM, kind: 'partition' },
    ...hallWalls
  ];
}

export function buildRooms(rawLayout) {
  const layout = normalizeLayout(rawLayout);
  const { variant, bathX, bathY, bathW, bathTop, bathBottom, hallX, hallY } = layout;

  const hall = {
    ...HALL_ROOM,
    polygon: [
      { x: 0, y: hallY },
      { x: hallX, y: hallY },
      { x: hallX, y: INNER_D },
      { x: 0, y: INNER_D }
    ]
  };

  if (variant === 'bathLeft') {
    // Санузел прижат к северной стене — зал начинается от его правой грани.
    // Если санузел опущен (например, чтобы не залезть на существующее окно),
    // полоса над ним тоже принадлежит залу.
    const livingPolygon = bathTop <= 0.01
      ? [
          { x: bathW, y: 0 },
          { x: INNER_W, y: 0 },
          { x: INNER_W, y: INNER_D },
          { x: hallX, y: INNER_D },
          { x: hallX, y: hallY },
          { x: 0, y: hallY },
          { x: 0, y: bathBottom },
          { x: bathW, y: bathBottom }
        ]
      : [
          { x: 0, y: 0 },
          { x: INNER_W, y: 0 },
          { x: INNER_W, y: INNER_D },
          { x: hallX, y: INNER_D },
          { x: hallX, y: hallY },
          { x: 0, y: hallY },
          { x: 0, y: bathBottom },
          { x: bathW, y: bathBottom },
          { x: bathW, y: bathTop },
          { x: 0, y: bathTop }
        ];

    return [
      { ...LIVING_ROOM, polygon: livingPolygon },
      {
        ...BATH_ROOM,
        polygon: [
          { x: 0, y: bathTop },
          { x: bathW, y: bathTop },
          { x: bathW, y: bathBottom },
          { x: 0, y: bathBottom }
        ]
      },
      hall
    ];
  }

  return [
    {
      ...LIVING_ROOM,
      // L-образный остаток: вырезаны санузел справа сверху и прихожая слева снизу
      polygon: [
        { x: 0, y: 0 },
        { x: bathX, y: 0 },
        { x: bathX, y: bathY },
        { x: INNER_W, y: bathY },
        { x: INNER_W, y: INNER_D },
        { x: hallX, y: INNER_D },
        { x: hallX, y: hallY },
        { x: 0, y: hallY }
      ]
    },
    {
      ...BATH_ROOM,
      polygon: [
        { x: bathX, y: 0 },
        { x: INNER_W, y: 0 },
        { x: INNER_W, y: bathY },
        { x: bathX, y: bathY }
      ]
    },
    hall
  ];
}

// Ручки перетаскивания перегородок — зависят от варианта.
export function partitionHandleDefs(rawLayout) {
  const layout = normalizeLayout(rawLayout);
  const { variant, bathX, bathY, bathW, bathTop, bathBottom, hallX, hallY } = layout;
  const hall = [
    { key: 'hallX', axis: 'x', x: hallX, y: hallY, len: INNER_D - hallY, label: 'Прихожая ←→' },
    { key: 'hallY', axis: 'y', x: 0, y: hallY, len: hallX, label: 'Прихожая ↑↓' }
  ];

  if (variant === 'bathLeft') {
    return [
      { key: 'bathW', axis: 'x', x: bathW, y: bathTop, len: bathBottom - bathTop, label: 'Санузел ←→' },
      { key: 'bathTop', axis: 'y', x: 0, y: bathTop, len: bathW, label: 'Санузел, верх ↑↓' },
      { key: 'bathBottom', axis: 'y', x: 0, y: bathBottom, len: bathW, label: 'Санузел, низ ↑↓' },
      ...hall
    ];
  }

  return [
    { key: 'bathX', axis: 'x', x: bathX, y: 0, len: bathY, label: 'Санузел ←→' },
    { key: 'bathY', axis: 'y', x: bathX, y: bathY, len: INNER_W - bathX, label: 'Санузел ↑↓' },
    ...hall
  ];
}

