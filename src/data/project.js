// Применяет вариант планировки: разбивка, проёмы, расстановка и те узлы,
// которые обязаны следовать за санузлом. Лестница и пирог пола не трогаются —
// они от варианта не зависят.
export function applyVariant(project, variantId) {
  const v = VARIANTS[variantId];
  if (!v) return project;
  return {
    ...project,
    layout: { ...DEFAULT_LAYOUT, ...v.layout },
    openings: v.openings.map((o) => ({ ...o })),
    equipment: v.equipment.map((e) => ({ ...e })),
    floorExclusionZones: (v.floorExclusionZones || []).map((z) => ({ ...z })),
    nodes: NODES.map((n) => (v.nodeOverrides[n.id] ? { ...n, ...v.nodeOverrides[n.id] } : { ...n }))
  };
}

// Ревизия СЧИТАЕТСЯ ИЗ СОДЕРЖИМОГО, а не проставляется руками.
//
// Четыре раза подряд менялись толщины, отметки и расстановка, а ревизия
// оставалась прежней — и сохранённый в браузере проект молча перетирал
// новые данные. Смета показывала старые объёмы, план старую геометрию,
// и каждый раз это выглядело как баг расчёта.
//
// Теперь любое изменение стартовых данных само даёт новое число.
// Забыть невозможно.
export function contentRevision(obj) {
  const json = JSON.stringify(obj);
  let h = 5381;
  for (let i = 0; i < json.length; i++) {
    h = ((h << 5) + h + json.charCodeAt(i)) | 0;
  }
  return Math.abs(h);
}

export function makeInitialProject(variantId = 'bathRight') {
  const base = {
    meta: { name: 'Floor Planner — 1 этаж', revision: 0, updatedAt: new Date().toISOString() },
    layout: { ...DEFAULT_LAYOUT },
    openings: [],
    stair: { ...STAIR },
    nodes: [],
    equipment: [],
    screed: { ...SCREED },
    levels: { ...LEVELS },
    ceiling: { ...CEILING },
    climate: { ...CLIMATE },
    envelope: JSON.parse(JSON.stringify(ENVELOPE)),
    boiler: { ...BOILER },
    coolant: { ...COOLANT },
    // Шаг укладки по помещениям; пусто — подбирается автоматически
    loopSpacings: {},
    // 'bifilar' — встречная укладка: рядом идут подача и обратка, пол греет ровно.
    // 'serpentine' — обычная змейка: у коллектора теплее, в глубине холоднее.
    loopMode: 'bifilar',
    // Кухня на открытом каркасе: бетонная столешница на стойках, под фронтом
    // остаётся продуваемый зазор. Тогда сплошные зоны без ТП не нужны —
    // исключаются только приборы, стоящие на полу.
    kitchenOnFrame: false
  };

  const project = applyVariant(base, variantId);
  // Хэш считаем по всему, кроме meta: updatedAt меняется каждый вызов
  const { meta, ...content } = project;
  project.meta = { ...meta, revision: contentRevision(content) };
  return project;
}
