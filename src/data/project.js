// Санузел не должен схлопнуться или налезть на прихожую.
export function normalizeLayout(l) {
  if (l.variant !== 'bathLeft') return l;
  const bathTop = Math.max(0, Math.min(l.bathTop, l.hallY - 0.9));
  const bathBottom = Math.max(bathTop + 0.9, Math.min(l.bathBottom, l.hallY));
  return { ...l, bathTop, bathBottom };
}

