// Объёмная теплоёмкость относительно воды: важна для инерции системы
export function volumetricRatio(coolant) {
  return (coolant.c * coolant.density) / (4.18 * 1000);
}

// Предельная длина петли ТП падает: вязкий состав даёт больше потерь.
// База для воды и трубы 16×2,0 — 90 м.
//
// Это ПРАВИЛО БОЛЬШОГО ПАЛЬЦА, а не расчёт. Настоящий критерий — хватает ли
// напора насоса, и его считает hydraulics.js. Если поверочный расчёт показал
// запас, предел можно поднять: coolant.maxLoopOverrideM.
// Сколько лет составу и вышел ли срок службы ингибиторов.
// Без ингибиторов этиленгликоль при перегреве разлагается до гликолевой
// и щавелевой кислот: pH падает, начинается коррозия. Паспорт котла
// требует pH 6,5…8,5.
export function coolantAge(coolant, now = new Date()) {
  if (!coolant?.manufactured) return null;
  const made = new Date(coolant.manufactured);
  const years = (now - made) / (365.25 * 24 * 3600 * 1000);
  return {
    years,
    shelfLifeYears: coolant.shelfLifeYears ?? null,
    expired: coolant.shelfLifeYears ? years > coolant.shelfLifeYears : null,
    overdueYears: coolant.shelfLifeYears ? years - coolant.shelfLifeYears : null
  };
}

export function maxLoopLength(coolant, waterLimitM = 90) {
  if (coolant?.maxLoopOverrideM) return coolant.maxLoopOverrideM;
  return waterLimitM / (coolant?.pressureDropFactor ?? 1) ** 0.5;
}
