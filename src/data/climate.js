// Градусо-сутки отопительного периода
export function gsop(climate) {
  return (climate.tInLiving - climate.tOutHeatingAvg) * climate.heatingDays;
}

// Нормируемое сопротивление теплопередаче стены жилого дома по СП 50.13330:
// R = a · ГСОП + b. Коэффициенты приведены по памяти и требуют сверки.
export const R_REQ_WALL = { a: 0.00035, b: 1.4, confirmed: false };

export function requiredWallR(climate, coef = R_REQ_WALL) {
  return coef.a * gsop(climate) + coef.b;
}

